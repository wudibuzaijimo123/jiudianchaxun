export function anjukeCitySlug(city?: string): string {
  const clean = String(city || '')
    .replace(/(特别行政区|自治区|自治州|地区|市|区|县)$/g, '')
    .trim();
  if (!clean) return '';
  if (CITY_SLUG[clean]) return CITY_SLUG[clean];
  for (const [name, slug] of Object.entries(CITY_SLUG)) {
    if (clean.startsWith(name) || String(city || '').includes(name)) {
      return slug;
    }
  }
  return '';
}

